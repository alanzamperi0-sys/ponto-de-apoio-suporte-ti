@st.cache_resource
def obter_pool_conexoes():
    return ThreadedConnectionPool(
        minconn=1,
        maxconn=5,
        host=st.secrets["postgres"]["host"],
        port=st.secrets["postgres"]["port"],
        dbname=st.secrets["postgres"]["dbname"],
        user=st.secrets["postgres"]["user"],
        password=st.secrets["postgres"]["password"],
        sslmode=st.secrets["postgres"]["sslmode"],
        cursor_factory=RealDictCursor,
        connect_timeout=10,
    )


def conectar_banco():
    return obter_pool_conexoes().getconn()


def devolver_conexao(conexao):
    obter_pool_conexoes().putconn(conexao)


@st.cache_resource
def inicializar_banco():
    """Cria a tabela uma única vez por execução do aplicativo."""
    conexao = conectar_banco()
    try:
        with conexao.cursor() as cursor:
            cursor.execute(
                """
                CREATE TABLE IF NOT EXISTS public.chamados (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    titulo TEXT NOT NULL,
                    solicitante TEXT NOT NULL,
                    categoria TEXT NOT NULL,
                    descricao TEXT NOT NULL,
                    status TEXT NOT NULL DEFAULT 'Aberto',
                    prioridade TEXT NOT NULL DEFAULT 'Média',
                    data TEXT NOT NULL
                )
                """
            )
        conexao.commit()
    except Exception:
        conexao.rollback()
        raise
    finally:
        devolver_conexao(conexao)
    return True


def listar_chamados():
    conexao = conectar_banco()
    try:
        with conexao.cursor() as cursor:
            cursor.execute("SELECT * FROM public.chamados ORDER BY id")
            linhas = cursor.fetchall()
            return [dict(linha) for linha in linhas]
    except Exception:
        conexao.rollback()
        raise
    finally:
        devolver_conexao(conexao)

def criar_chamado(
    titulo, solicitante, categoria, descricao, prioridade
):
    data_abertura = datetime.now().strftime("%d/%m/%Y %H:%M")
    conexao = conectar_banco()
    try:
        with conexao.cursor() as cursor:
            cursor.execute(
                """
                INSERT INTO public.chamados
                    (titulo, solicitante, categoria, descricao,
                     status, prioridade, data)
                VALUES (%s, %s, %s, %s, %s, %s, %s)
                RETURNING id
                """,
                (
                    titulo,
                    solicitante,
                    categoria,
                    descricao,
                    "Aberto",
                    prioridade,
                    data_abertura,
                ),
            )
            novo_chamado = cursor.fetchone()
        conexao.commit()
        return novo_chamado["id"]
    except Exception:
        conexao.rollback()
        raise
    finally:
        devolver_conexao(conexao)


def atualizar_status(chamado_id, novo_status):
    conexao = conectar_banco()
    try:
        with conexao.cursor() as cursor:
            cursor.execute(
                """
                UPDATE public.chamados
                SET status = %s
                WHERE id = %s
                """,
                (novo_status, chamado_id),
            )
        conexao.commit()
    except Exception:
        conexao.rollback()
        raise
    finally:
        devolver_conexao(conexao)


